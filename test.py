# ============================================================
# Print Class-wise Results
# ============================================================

def print_classwise_results(
    classwise,
):

    print("\n")
    print("CLASS-WISE TEST RESULTS")
    print("=" * 85)

    print(
        f"{'Class':<18}"
        f"{'Precision':>15}"
        f"{'Recall':>15}"
        f"{'F1-score':>15}"
        f"{'Support':>12}"
    )

    print("-" * 85)

    for class_name in CLASS_NAMES:

        values = classwise[
            class_name
        ]

        print(
            f"{class_name:<18}"
            f"{values['precision'] * 100:>14.2f}%"
            f"{values['recall'] * 100:>14.2f}%"
            f"{values['f1'] * 100:>14.2f}%"
            f"{values['support']:>12}"
        )

    print("-" * 85)


# ============================================================
# Print Confusion Matrix
# ============================================================

def print_confusion_matrix(
    cm,
):

    print("\n")
    print("CONFUSION MATRIX")
    print("=" * 70)

    print(
        f"{'True / Pred':<18}"
        + "".join(
            f"{name:>14}"
            for name in CLASS_NAMES
        )
    )

    print("-" * 70)

    for i, class_name in enumerate(
        CLASS_NAMES
    ):

        row = (
            f"{class_name:<18}"
            + "".join(
                f"{cm[i, j]:>14}"
                for j in range(NUM_CLASSES)
            )
        )

        print(row)

    print("-" * 70)


# ============================================================
# Save Predictions
# ============================================================

def save_predictions(
    y_true,
    y_pred,
    y_prob,
    output_path,
):

    output_path = Path(
        output_path
    )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    fieldnames = [
        "sample_index",
        "true_label",
        "true_class",
        "predicted_label",
        "predicted_class",
        "confidence",
    ]

    for class_name in CLASS_NAMES:

        fieldnames.append(
            f"prob_{class_name.lower().replace('-', '_')}"
        )

    with open(
        output_path,
        "w",
        newline="",
        encoding="utf-8",
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fieldnames,
        )

        writer.writeheader()

        for i in range(
            len(y_true)
        ):

            predicted_probability = float(
                y_prob[i, y_pred[i]]
            )

            row = {
                "sample_index": i,
                "true_label": int(
                    y_true[i]
                ),
                "true_class": CLASS_NAMES[
                    y_true[i]
                ],
                "predicted_label": int(
                    y_pred[i]
                ),
                "predicted_class": CLASS_NAMES[
                    y_pred[i]
                ],
                "confidence":
                    predicted_probability,
            }

            for class_index, class_name in enumerate(
                CLASS_NAMES
            ):

                column_name = (
                    "prob_"
                    + class_name.lower()
                    .replace("-", "_")
                )

                row[column_name] = float(
                    y_prob[
                        i,
                        class_index
                    ]
                )

            writer.writerow(row)


# ============================================================
# Save Results
# ============================================================

def save_results(
    metrics,
    classwise,
    cm,
    output_path,
):

    output_path = Path(
        output_path
    )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    results = {
        "overall": {
            key: (
                None
                if np.isnan(value)
                else float(value)
            )
            for key, value in metrics.items()
        },
        "classwise": classwise,
        "confusion_matrix": cm.tolist(),
    }

    with open(
        output_path,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            results,
            file,
            indent=4,
        )


# ============================================================
# Save Confusion Matrix
# ============================================================

def save_confusion_matrix(
    cm,
    output_path,
):

    output_path = Path(
        output_path
    )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    np.savetxt(
        output_path,
        cm,
        delimiter=",",
        fmt="%d",
    )


# ============================================================
# Main
# ============================================================

def main():

    parser = argparse.ArgumentParser(
        description=(
            "Evaluate CSA-ViT on the "
            "patient-level internal held-out test set."
        )
    )

    # --------------------------------------------------------
    # Dataset
    # --------------------------------------------------------

    parser.add_argument(
        "--data_dir",
        type=str,
        required=True,
        help="Root directory containing MRI data.",
    )

    parser.add_argument(
        "--test_csv",
        type=str,
        required=True,
        help=(
            "CSV file containing ONLY the "
            "patient-level held-out test split."
        ),
    )

    # --------------------------------------------------------
    # Checkpoint
    # --------------------------------------------------------

    parser.add_argument(
        "--checkpoint",
        type=str,
        required=True,
        help="Path to csavit_best.pth.",
    )

    # --------------------------------------------------------
    # Evaluation
    # --------------------------------------------------------

    parser.add_argument(
        "--batch_size",
        type=int,
        default=32,
    )

    parser.add_argument(
        "--num_workers",
        type=int,
        default=4,
    )

    parser.add_argument(
        "--output_dir",
        type=str,
        default="results/test",
    )

    parser.add_argument(
        "--seed",
        type=int,
        default=42,
    )

    args = parser.parse_args()

    # ========================================================
    # Reproducibility
    # ========================================================

    set_seed(
        args.seed
    )

    # ========================================================
    # Device
    # ========================================================

    device = get_device()

    print("=" * 70)
    print("CSA-ViT TEST EVALUATION")
    print("=" * 70)

    print(
        f"Device     : {device}"
    )

    if torch.cuda.is_available():

        print(
            f"GPU        : "
            f"{torch.cuda.get_device_name(0)}"
        )

    print(
        f"Checkpoint : "
        f"{args.checkpoint}"
    )

    print(
        f"Test CSV   : "
        f"{args.test_csv}"
    )

    print("=" * 70)

    # ========================================================
    # Test Dataset
    # ========================================================

    test_dataset = BrainMRIDataset(
        data_dir=args.data_dir,
        csv_file=args.test_csv,
        image_size=224,
        train=False,
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=args.batch_size,
        shuffle=False,
        num_workers=args.num_workers,
        pin_memory=torch.cuda.is_available(),
        drop_last=False,
    )

    print(
        f"\nTest samples: "
        f"{len(test_dataset)}"
    )

    # ========================================================
    # Build Model
    # ========================================================

    model = build_model()

    # ========================================================
    # Load Best Checkpoint
    # ========================================================

    model = load_checkpoint(
        model=model,
        checkpoint_path=args.checkpoint,
        device=device,
    )

    model = model.to(
        device
    )

    model.eval()

    print(
        "\nBest CSA-ViT checkpoint loaded successfully."
    )

    # ========================================================
    # Run Test
    # ========================================================

    (
        y_true,
        y_pred,
        y_prob,
    ) = run_test(
        model=model,
        dataloader=test_loader,
        device=device,
    )

    # ========================================================
    # Validate Number of Test Samples
    # ========================================================

    if len(y_true) != 270:

        print(
            "\nWARNING:"
            f" Manuscript expects 270 test samples, "
            f"but {len(y_true)} samples were evaluated."
        )

    else:

        print(
            "\nThe evaluation contains the "
            "expected 270 held-out test samples."
        )

    # ========================================================
    # Test Distribution
    # ========================================================

    validate_test_distribution(
        y_true
    )

    # ========================================================
    # Overall Metrics
    # ========================================================

    metrics = calculate_metrics(
        y_true=y_true,
        y_pred=y_pred,
        y_prob=y_prob,
    )

    print_overall_results(
        metrics
    )

    # ========================================================
    # Class-wise Metrics
    # ========================================================

    classwise = calculate_classwise_metrics(
        y_true=y_true,
        y_pred=y_pred,
    )

    print_classwise_results(
        classwise
    )

    # ========================================================
    # Confusion Matrix
    # ========================================================

    cm = confusion_matrix(
        y_true,
        y_pred,
        labels=np.arange(
            NUM_CLASSES
        ),
    )

    print_confusion_matrix(
        cm
    )

    # ========================================================
    # Output Directory
    # ========================================================

    output_dir = Path(
        args.output_dir
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    # ========================================================
    # Save Overall Results
    # ========================================================

    save_results(
        metrics=metrics,
        classwise=classwise,
        cm=cm,
        output_path=(
            output_dir
            / "test_results.json"
        ),
    )

    # ========================================================
    # Save Confusion Matrix
    # ========================================================

    save_confusion_matrix(
        cm=cm,
        output_path=(
            output_dir
            / "confusion_matrix.csv"
        ),
    )

    # ========================================================
    # Save Predictions and Probabilities
    # ========================================================

    save_predictions(
        y_true=y_true,
        y_pred=y_pred,
        y_prob=y_prob,
        output_path=(
            output_dir
            / "test_predictions.csv"
        ),
    )

    # ========================================================
    # Save Human-readable Results
    # ========================================================

    with open(
        output_dir / "test_results.txt",
        "w",
        encoding="utf-8",
    ) as file:

        file.write(
            "CSA-ViT Internal Held-out Test Results\n"
        )

        file.write(
            "=" * 60 + "\n\n"
        )

        file.write(
            f"Number of test samples: "
            f"{len(y_true)}\n\n"
        )

        file.write(
            f"Accuracy: "
            f"{metrics['accuracy'] * 100:.4f}%\n"
        )

        file.write(
            f"Macro Precision: "
            f"{metrics['precision'] * 100:.4f}%\n"
        )

        file.write(
            f"Macro Recall: "
            f"{metrics['recall'] * 100:.4f}%\n"
        )

        file.write(
            f"Macro F1: "
            f"{metrics['f1'] * 100:.4f}%\n"
        )

        if np.isnan(
            metrics["auc"]
        ):

            file.write(
                "Macro One-vs-Rest AUC: N/A\n"
            )

        else:

            file.write(
                f"Macro One-vs-Rest AUC: "
                f"{metrics['auc'] * 100:.4f}%\n"
            )

        file.write(
            "\nClass-wise Results\n"
        )

        file.write(
            "-" * 60 + "\n"
        )

        for class_name in CLASS_NAMES:

            values = classwise[
                class_name
            ]

            file.write(
                f"\n{class_name}\n"
            )

            file.write(
                f"Precision: "
                f"{values['precision'] * 100:.4f}%\n"
            )

            file.write(
                f"Recall: "
                f"{values['recall'] * 100:.4f}%\n"
            )

            file.write(
                f"F1-score: "
                f"{values['f1'] * 100:.4f}%\n"
            )

            file.write(
                f"Support: "
                f"{values['support']}\n"
            )

        file.write(
            "\nConfusion Matrix\n"
        )

        file.write(
            str(cm)
        )

        file.write(
            "\n"
        )

    # ========================================================
    # Final Information
    # ========================================================

    print("\n")
    print("=" * 70)
    print("TEST EVALUATION COMPLETED")
    print("=" * 70)

    print(
        f"Results directory : "
        f"{output_dir}"
    )

    print(
        f"Results JSON      : "
        f"{output_dir / 'test_results.json'}"
    )

    print(
        f"Results TXT       : "
        f"{output_dir / 'test_results.txt'}"
    )

    print(
        f"Predictions CSV   : "
        f"{output_dir / 'test_predictions.csv'}"
    )

    print(
        f"Confusion Matrix  : "
        f"{output_dir / 'confusion_matrix.csv'}"
    )

    print("=" * 70)


# ============================================================
# Entry Point
# ============================================================

if __name__ == "__main__":
    main()
