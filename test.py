"""
CSA-ViT Test / Evaluation Script
================================

Evaluates a trained CSA-ViT model on the patient-level internal
held-out test set described in the manuscript.

Manuscript configuration
------------------------
Dataset:
    1,800 MRI samples
    200 patients
    4 classes
        0 - No-tumor
        1 - Glioma
        2 - Meningioma
        3 - Pituitary

Patient-level split:
    70% training
    15% validation
    15% test

Internal test set:
    270 samples
    67 No-tumor
    68 Glioma
    67 Meningioma
    68 Pituitary

Model:
    CSA-ViT
    Input: 224 x 224
    Four MRI sequences: T1, T1CE, T2, FLAIR
    Embedding dimension: 256
    Patch sizes: 8, 16, 32
    HCSAM: 6 blocks, 8 heads
    Transformer encoder: 6 layers
    Dropout: 0.1

Reported test metrics:
    Accuracy
    Macro Precision
    Macro Recall
    Macro F1
    Macro One-vs-Rest AUC

Additional outputs:
    Class-wise precision / recall / F1
    Confusion matrix
    Predicted probabilities
    Test predictions CSV

IMPORTANT:
    This script evaluates ONLY the held-out test partition.

    The manuscript's Figure 4 is a descriptive confusion matrix
    across the complete 1,800-sample dataset. The confusion matrix
    generated here is specifically for the 270-sample held-out
    internal test set and should not automatically replace Figure 4
    unless the manuscript is revised accordingly.
"""

import argparse
import csv
import json
import os
import random
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import DataLoader

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    confusion_matrix,
)

from models.csavit import CSAViT
from data.dataset import BrainMRIDataset


# ============================================================
# Constants
# ============================================================

CLASS_NAMES = [
    "No-tumor",
    "Glioma",
    "Meningioma",
    "Pituitary",
]

NUM_CLASSES = 4

EXPECTED_TEST_COUNTS = {
    "No-tumor": 67,
    "Glioma": 68,
    "Meningioma": 67,
    "Pituitary": 68,
}


# ============================================================
# Reproducibility
# ============================================================

def set_seed(seed=42):
    """
    Set random seeds for deterministic evaluation.
    """

    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)

    if torch.cuda.is_available():
        torch.cuda.manual_seed(seed)
        torch.cuda.manual_seed_all(seed)

    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


# ============================================================
# Device
# ============================================================

def get_device():

    if torch.cuda.is_available():
        return torch.device("cuda")

    return torch.device("cpu")


# ============================================================
# CSA-ViT Model
# ============================================================

def build_model():

    model = CSAViT(
        in_channels=4,
        stem_channels=(64, 128),
        embed_dim=256,
        patch_sizes=(8, 16, 32),
        hcsam_blocks=6,
        heads=8,
        transformer_layers=6,
        dropout=0.1,
        num_classes=NUM_CLASSES,
    )

    return model


# ============================================================
# Load Checkpoint
# ============================================================

def load_checkpoint(
    model,
    checkpoint_path,
    device,
):

    checkpoint = torch.load(
        checkpoint_path,
        map_location=device,
    )

    # --------------------------------------------------------
    # Checkpoint generated by train.py
    # --------------------------------------------------------

    if (
        isinstance(checkpoint, dict)
        and "model_state_dict" in checkpoint
    ):

        state_dict = checkpoint[
            "model_state_dict"
        ]

    # --------------------------------------------------------
    # Plain state_dict
    # --------------------------------------------------------

    else:

        state_dict = checkpoint

    model.load_state_dict(
        state_dict,
        strict=True,
    )

    return model


# ============================================================
# Test Inference
# ============================================================

@torch.no_grad()
def run_test(
    model,
    dataloader,
    device,
):

    model.eval()

    all_labels = []
    all_predictions = []
    all_probabilities = []

    for batch in dataloader:

        # ----------------------------------------------------
        # Dataset output
        #
        # Expected:
        #     images, labels
        #
        # Optional:
        #     images, labels, metadata
        # ----------------------------------------------------

        images = batch[0]
        labels = batch[1]

        images = images.to(
            device,
            non_blocking=True,
        )

        labels = labels.to(
            device,
            non_blocking=True,
        )

        # ----------------------------------------------------
        # Forward pass
        # ----------------------------------------------------

        output = model(images)

        # ----------------------------------------------------
        # Support both tensor and dictionary outputs
        # ----------------------------------------------------

        if isinstance(output, dict):

            logits = output["logits"]

        else:

            logits = output

        # ----------------------------------------------------
        # Convert logits to probabilities
        # ----------------------------------------------------

        probabilities = torch.softmax(
            logits,
            dim=1,
        )

        predictions = torch.argmax(
            probabilities,
            dim=1,
        )

        # ----------------------------------------------------
        # Store predictions
        # ----------------------------------------------------

        all_labels.extend(
            labels.cpu().numpy().tolist()
        )

        all_predictions.extend(
            predictions.cpu().numpy().tolist()
        )

        all_probabilities.append(
            probabilities.cpu()
        )

    y_true = np.asarray(
        all_labels,
        dtype=np.int64,
    )

    y_pred = np.asarray(
        all_predictions,
        dtype=np.int64,
    )

    y_prob = torch.cat(
        all_probabilities,
        dim=0,
    ).numpy()

    return (
        y_true,
        y_pred,
        y_prob,
    )


# ============================================================
# Calculate Overall Metrics
# ============================================================

def calculate_metrics(
    y_true,
    y_pred,
    y_prob,
):

    metrics = {}

    metrics["accuracy"] = accuracy_score(
        y_true,
        y_pred,
    )

    metrics["precision"] = precision_score(
        y_true,
        y_pred,
        average="macro",
        zero_division=0,
    )

    metrics["recall"] = recall_score(
        y_true,
        y_pred,
        average="macro",
        zero_division=0,
    )

    metrics["f1"] = f1_score(
        y_true,
        y_pred,
        average="macro",
        zero_division=0,
    )

    try:

        metrics["auc"] = roc_auc_score(
            y_true,
            y_prob,
            multi_class="ovr",
            average="macro",
            labels=np.arange(NUM_CLASSES),
        )

    except ValueError:

        metrics["auc"] = float("nan")

    return metrics


# ============================================================
# Class-wise Metrics
# ============================================================

def calculate_classwise_metrics(
    y_true,
    y_pred,
):

    precision = precision_score(
        y_true,
        y_pred,
        average=None,
        labels=np.arange(NUM_CLASSES),
        zero_division=0,
    )

    recall = recall_score(
        y_true,
        y_pred,
        average=None,
        labels=np.arange(NUM_CLASSES),
        zero_division=0,
    )

    f1 = f1_score(
        y_true,
        y_pred,
        average=None,
        labels=np.arange(NUM_CLASSES),
        zero_division=0,
    )

    support = np.bincount(
        y_true,
        minlength=NUM_CLASSES,
    )

    results = {}

    for index, class_name in enumerate(
        CLASS_NAMES
    ):

        results[class_name] = {
            "precision": float(
                precision[index]
            ),
            "recall": float(
                recall[index]
            ),
            "f1": float(
                f1[index]
            ),
            "support": int(
                support[index]
            ),
        }

    return results


# ============================================================
# Validate Test Distribution
# ============================================================

def validate_test_distribution(
    y_true,
):

    print("\nTest-set class distribution")
    print("-" * 60)

    total = len(y_true)

    for index, class_name in enumerate(
        CLASS_NAMES
    ):

        count = int(
            np.sum(
                y_true == index
            )
        )

        expected = EXPECTED_TEST_COUNTS[
            class_name
        ]

        print(
            f"{class_name:<15}"
            f"Observed: {count:<5}"
            f"Expected: {expected:<5}"
        )

    print("-" * 60)
    print(f"Total test samples: {total}")

    expected_total = sum(
        EXPECTED_TEST_COUNTS.values()
    )

    if total != expected_total:

        print(
            "\nWARNING:"
            f" Expected {expected_total} "
            f"test samples but found {total}."
        )


